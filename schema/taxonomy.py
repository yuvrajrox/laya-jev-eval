# Questions carrying a hard label in the canonical record. `hostility` is ordinal and
# `revisit_later` is subtle, so both are teacher-labelled rather than hand-labelled.
LABELLED = ["intent", "meeting_booked", "is_human"]

# --------------------------------------------------------------------------- canonical record
# One row of the corpus. ingest.py emits this shape; everything else consumes it.
#
# {
#   "id":            "rox-000123",            stable, survives re-runs
#   "source":        "rox_prod" | "rox_dev" | "enron" | "spamassassin" | "synthetic",
#   "subject":       "Re: quick question",
#   "body":          cleaned reply text, quoted thread and signature removed
#   "body_raw":      the original, kept for audit
#   "thread":        ["...older turns, newest last..."],   may be []
#   "account":       {"name": "Acme", "industry": "..."},  may be {}
#   "lang":          "en" | ISO code | null
#   "labels":        {"intent": "ooo", "meeting_booked": false, "is_human": false}
#   "label_source":  "human" | "user_action" | "teacher" | "rule" | "synthetic"
#   "soft":          {"intent": [...7 floats...]}  teacher distribution, optional
#   "split":         "eval" | "train" | null
# }

REQUIRED_FIELDS = ["id", "source", "body", "labels", "label_source"]


def state_for(rec, include_thread=True, max_thread_turns=3):
    """Canonical record -> the `state` dict handed to Laya.

    Keep this stable between eval and training: the model is trained on whatever
    serialisation you pick here, and changing it at inference silently degrades
    accuracy. Thread turns are truncated because the English checkpoint has a 512
    token budget and roughly 320 of it is left for state after the option head.
    """
    state = {"subject": rec.get("subject") or "", "body": rec.get("body") or ""}
    thread = rec.get("thread") or []
    if include_thread and thread:
        state["thread"] = thread[-max_thread_turns:]
    account = rec.get("account") or {}
    if account.get("name"):
        state["account"] = account.get("name")
    return state


# --------------------------------------------------------------------------- user-action mapping
# Rox UI actions that are already ground truth. From the product brief: batch actions
# can mark Interested / Replied / Meeting Booked / Unsubscribed, and contacts move
# through Not Started / Started / Paused / Replied / Interested / Not Interested /
# Finished-No Reply / Needs Attention.
#
# quality "gold"  -> a human deliberately asserted this; trust it, upweight it
# quality "weak"  -> inferred from a state transition; send it to the teacher instead

USER_ACTION_LABELS = {
    "mark_interested":     ({"intent": "interested"},      "gold"),
    "mark_not_interested": ({"intent": "not_interested"},  "gold"),
    "mark_unsubscribed":   ({"intent": "unsubscribe"},     "gold"),
    "mark_meeting_booked": ({"meeting_booked": True},      "gold"),
    "state_paused":        ({"intent": "ooo"},             "weak"),
    "state_needs_attention": ({},                          "weak"),
}
