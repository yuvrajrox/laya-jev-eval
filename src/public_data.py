"""Mine real out-of-office autoreplies and bounces from the SpamAssassin public corpus.

Why only these two classes: they are ~70% of real reply volume, they are generated by
mail servers and autoresponders rather than people, and their wording has not changed
since 2001 -- so public data from 2002 transfers perfectly. Nothing else in a public
corpus is in-distribution for replies to cold outbound, so nothing else is taken.

Deliberately capped. Flooding the corpus with easy automated messages makes every
headline metric go up while teaching you nothing about the classes that matter.

    python3 src/public_data.py --out data/public/spamassassin_auto.csv --limit 150
"""
import argparse
import csv
import email
import os
import sys
import tarfile
import urllib.request
from email import policy

sys.path.insert(0, os.path.dirname(__file__))
from clean import detect_automated  # noqa: E402

BASE = "https://spamassassin.apache.org/old/publiccorpus/"
ARCHIVES = ["20030228_easy_ham.tar.bz2", "20030228_hard_ham.tar.bz2"]


def download(url, dest):
    if os.path.exists(dest):
        print("  cached %s" % os.path.basename(dest))
        return dest
    print("  downloading %s ..." % os.path.basename(dest))
    urllib.request.urlretrieve(url, dest)
    return dest


def body_of(msg, max_chars=4000):
    if msg.is_multipart():
        for part in msg.walk():
            if part.get_content_type() == "text/plain":
                try:
                    return part.get_content()[:max_chars]
                except Exception:                    # noqa: BLE001
                    continue
        return ""
    try:
        return (msg.get_content() or "")[:max_chars]
    except Exception:                                # noqa: BLE001
        return ""


def mine(tar_path, limit_per_class):
    rows, counts = [], {"ooo": 0, "bounce": 0}
    with tarfile.open(tar_path, "r:bz2") as tf:
        for member in tf:
            if not member.isfile() or all(c >= limit_per_class for c in counts.values()):
                continue
            try:
                msg = email.message_from_binary_file(tf.extractfile(member), policy=policy.default)
            except Exception:                        # noqa: BLE001
                continue
            subject = str(msg.get("Subject") or "")
            sender = str(msg.get("From") or "")
            headers = "\n".join("%s: %s" % (k, v) for k, v in msg.items()).lower()
            label = detect_automated(subject=subject, sender=sender, headers=headers)
            if not label or counts[label] >= limit_per_class:
                continue
            body = body_of(msg)
            if len(body.strip()) < 20:
                continue
            counts[label] += 1
            rows.append({"id": "sa-%s" % os.path.basename(member.name), "subject": subject,
                         "from": sender, "body": body, "intent": label, "is_human": "false",
                         "headers": headers[:2000]})
    return rows, counts


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="data/public/spamassassin_auto.csv")
    ap.add_argument("--cache", default="data/public/_archives")
    ap.add_argument("--limit", type=int, default=150, help="cap per class")
    args = ap.parse_args()

    os.makedirs(args.cache, exist_ok=True)
    os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)

    rows, total = [], {"ooo": 0, "bounce": 0}
    for name in ARCHIVES:
        try:
            path = download(BASE + name, os.path.join(args.cache, name))
        except Exception as e:                       # noqa: BLE001
            print("  ! %s: %s" % (name, e))
            continue
        r, c = mine(path, args.limit)
        rows += r
        for k, v in c.items():
            total[k] += v

    if not rows:
        sys.exit("nothing mined -- check network access to spamassassin.apache.org")

    with open(args.out, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=["id", "subject", "from", "body", "intent", "is_human", "headers"])
        w.writeheader()
        w.writerows(rows)
    print("\n%d rows -> %s" % (len(rows), args.out))
    for k, v in total.items():
        print("  %-8s %d" % (k, v))
    print("\nThese are RULE-labelled from headers and subject, which is >99%% precise for")
    print("these two classes. Spot-check 20 by hand anyway before training on them.")
    print("Next: python3 src/ingest.py %s --source spamassassin --out data/interim/corpus.jsonl --append" % args.out)


if __name__ == "__main__":
    main()
